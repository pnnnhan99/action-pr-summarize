import * as core from '@actions/core';
import * as github from '@actions/github';
import { Octokit } from '@octokit/rest';
import OpenAI from 'openai';

// System prompt for AI to act as a Technical Writer
const SYSTEM_PROMPT = `You are an expert Technical Writer and Code Analyst. Your role is to analyze Pull Request changes and translate technical code changes into clear, business-focused summaries for non-technical stakeholders (Product Managers, QA Engineers, Business Analysts).

Your goal is to explain:
1. What business value or user impact this change brings
2. What features are being added, modified, or removed
3. What potential risks or areas need QA attention
4. Any breaking changes or migration requirements

Format your response as follows:

## 📋 Summary
[Brief 2-3 sentence overview of what this PR accomplishes]

## ✨ Key Changes
- [Change 1]: Brief description of what changed and why
- [Change 2]: Brief description of what changed and why
- [Change 3]: Brief description of what changed and why

## 🎯 Business Impact
[Explain the business value: what users will experience, what problems this solves, or what improvements this brings]

## ⚠️ Areas for QA Focus
- [Specific areas that need testing attention]
- [Edge cases or scenarios to verify]
- [Any potential regressions to watch for]

## 📝 Notes
[Any additional context, dependencies, or follow-up items]

Keep your response concise, actionable, and free of unnecessary technical jargon. Focus on the "what" and "why" rather than the "how."`;

const COMMENT_MARKER = '<!-- pr-summarizer-action -->';

/**
 * Filters files based on ignored patterns
 */
function shouldIgnoreFile(filename: string, ignoredPatterns: string[]): boolean {
  return ignoredPatterns.some(pattern => {
    const regex = new RegExp(
      pattern
        .replace(/\*/g, '.*')
        .replace(/\?/g, '.')
    );
    return regex.test(filename);
  });
}

/**
 * Fetches and filters PR diff
 */
async function getPRDiff(
  octokit: Octokit,
  owner: string,
  repo: string,
  pullNumber: number,
  ignoredPatterns: string[],
  maxLength: number
): Promise<string> {
  try {
    core.info(`Fetching diff for PR #${pullNumber}...`);

    const { data: files } = await octokit.rest.pulls.listFiles({
      owner,
      repo,
      pull_number: pullNumber,
    });

    let diff = '';
    let totalLength = 0;

    for (const file of files) {
      if (shouldIgnoreFile(file.filename, ignoredPatterns)) {
        core.info(`Ignoring file: ${file.filename}`);
        continue;
      }

      if (file.patch) {
        const fileHeader = `\n\n### File: ${file.filename} (${file.status})\n`;
        const fileDiff = fileHeader + file.patch;

        if (totalLength + fileDiff.length > maxLength) {
          const remainingSpace = maxLength - totalLength;
          if (remainingSpace > 100) {
            diff += fileDiff.substring(0, remainingSpace) + '\n\n[... diff truncated due to length ...]';
          }
          core.warning(`Diff truncated to ${maxLength} characters to save tokens`);
          break;
        }

        diff += fileDiff;
        totalLength += fileDiff.length;
      }
    }

    if (!diff) {
      throw new Error('No relevant changes found after filtering files');
    }

    core.info(`Fetched diff with ${totalLength} characters from ${files.length} files`);
    return diff.trim();
  } catch (error) {
    if (error instanceof Error) {
      core.error(`Failed to fetch PR diff: ${error.message}`);
      throw error;
    }
    throw new Error('Unknown error fetching PR diff');
  }
}

/**
 * Generates summary using OpenAI API
 */
async function generateSummary(
  diff: string,
  apiKey: string,
  model: string
): Promise<string> {
  try {
    core.info('Generating AI summary...');

    const openai = new OpenAI({
      apiKey: apiKey,
    });

    const response = await openai.chat.completions.create({
      model: model,
      messages: [
        {
          role: 'system',
          content: SYSTEM_PROMPT,
        },
        {
          role: 'user',
          content: `Please analyze the following Pull Request diff and provide a summary:\n\n\`\`\`diff\n${diff}\n\`\`\``,
        },
      ],
      temperature: 0.7,
      max_tokens: 2000,
    });

    const summary = response.choices[0]?.message?.content;
    if (!summary) {
      throw new Error('No summary generated by AI');
    }

    core.info('AI summary generated successfully');
    return summary;
  } catch (error) {
    if (error instanceof Error) {
      core.error(`Failed to generate summary: ${error.message}`);
      throw error;
    }
    throw new Error('Unknown error generating summary');
  }
}

/**
 * Finds existing comment by marker
 */
async function findExistingComment(
  octokit: Octokit,
  owner: string,
  repo: string,
  pullNumber: number
): Promise<number | null> {
  try {
    const { data: comments } = await octokit.rest.issues.listComments({
      owner,
      repo,
      issue_number: pullNumber,
    });

    const botComment = comments.find(comment =>
      comment.body?.includes(COMMENT_MARKER)
    );

    return botComment?.id || null;
  } catch (error) {
    core.warning(`Failed to find existing comment: ${error instanceof Error ? error.message : 'Unknown error'}`);
    return null;
  }
}

/**
 * Creates or updates comment on PR
 */
async function upsertComment(
  octokit: Octokit,
  owner: string,
  repo: string,
  pullNumber: number,
  body: string
): Promise<void> {
  try {
    const commentBody = `${COMMENT_MARKER}\n\n${body}`;

    const existingCommentId = await findExistingComment(octokit, owner, repo, pullNumber);

    if (existingCommentId) {
      core.info(`Updating existing comment #${existingCommentId}...`);
      await octokit.rest.issues.updateComment({
        owner,
        repo,
        comment_id: existingCommentId,
        body: commentBody,
      });
      core.info('Comment updated successfully');
    } else {
      core.info('Creating new comment...');
      await octokit.rest.issues.createComment({
        owner,
        repo,
        issue_number: pullNumber,
        body: commentBody,
      });
      core.info('Comment created successfully');
    }
  } catch (error) {
    if (error instanceof Error) {
      core.error(`Failed to upsert comment: ${error.message}`);
      throw error;
    }
    throw new Error('Unknown error upserting comment');
  }
}

/**
 * Main function
 */
async function run(): Promise<void> {
  try {
    const githubToken = core.getInput('github-token', { required: true });
    const openaiApiKey = core.getInput('openai-api-key', { required: true });
    const model = core.getInput('model') || 'gpt-4o-mini';
    const maxLength = parseInt(core.getInput('max-diff-length') || '50000', 10);
    const ignoredFilesInput = core.getInput('ignored-files') || '*.lock,*.svg,*.csv,*.min.js,*.min.css,package-lock.json,yarn.lock,pnpm-lock.yaml';
    const ignoredPatterns = ignoredFilesInput.split(',').map(p => p.trim());

    const context = github.context;
    const { owner, repo, number: pullNumber } = context.payload.pull_request || {};

    if (!owner || !repo || !pullNumber) {
      throw new Error('This action can only be run on Pull Request events');
    }

    core.info(`Processing PR #${pullNumber} in ${owner}/${repo}`);

    const octokit = new Octokit({
      auth: githubToken,
    });

    // Step 1: Fetch and filter PR diff
    const diff = await getPRDiff(octokit, owner, repo, pullNumber, ignoredPatterns, maxLength);

    // Step 2: Generate AI summary
    const summary = await generateSummary(diff, openaiApiKey, model);

    // Step 3: Upsert comment on PR
    await upsertComment(octokit, owner, repo, pullNumber, summary);

    // Set output
    core.setOutput('summary', summary);

    core.info('Action completed successfully');
  } catch (error) {
    if (error instanceof Error) {
      core.setFailed(`Action failed: ${error.message}`);
    } else {
      core.setFailed('Action failed with unknown error');
    }
  }
}

// Run the action
if (require.main === module) {
  run();
}

export { run, getPRDiff, generateSummary, upsertComment };
